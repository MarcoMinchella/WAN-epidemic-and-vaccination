def _entropy(labels):
    labels = np.asarray(labels)
    _, c = np.unique(labels, return_counts=True)
    p = c / c.sum()
    return -np.sum(p * np.log(p))

def nvi(a, b):
    a = np.asarray(a)
    b = np.asarray(b)
    n = a.size
    Ha = _entropy(a)
    Hb = _entropy(b)
    I  = mutual_info_score(a, b)
    vi = Ha + Hb - 2.0 * I
    return vi / np.log(n)


def consensus_clustering(partitions, resolution=1.0, tau=0.5,
                         max_iter=10, n_reclust=5, verbose=False):
    partitions = [np.asarray(p) for p in partitions]
    n_nodes = partitions[0].size

    for it in range(max_iter):
        D = np.zeros((n_nodes, n_nodes), dtype=np.float32)
        for p in partitions:
            same = (p[:, None] == p[None, :])
            D += same
        D /= len(partitions)

        D[D < tau] = 0.0
        np.fill_diagonal(D, 0.0)

        g = ig.Graph.Weighted_Adjacency(D, mode="undirected", loops=False)

        comp = g.connected_components(mode="weak")
        new_partitions = [np.asarray(comp.membership)] * n_reclust

        if len(set(comp.membership)) < n_nodes:
            new_partitions = [
                np.asarray(louvain.find_partition(
                    g, louvain.RBConfigurationVertexPartition,
                    resolution_parameter=resolution,
                    weights="weight").membership)
                for _ in range(n_reclust)
            ]

        if all((new_partitions[0] == q).all() for q in new_partitions[1:]):
            if verbose:
                print(f"    consensus converged in {it+1} iter")
            return new_partitions[0]

        partitions = new_partitions

    return partitions[0]

