#Helper functions
def log_binned_mixing(G, x="out", y="in", edge_weight="weight", nbins=25):
    dx = dict(G.out_degree(weight=None)) if x == "out" else dict(G.in_degree(weight=None))
    dy = dict(G.out_degree(weight=None)) if y == "out" else dict(G.in_degree(weight=None))

    max_x = max(dx.values(), default=0)
    max_y = max(dy.values(), default=0)

    x_edges = np.unique(np.r_[0, 1, np.logspace(0, np.log10(max_x + 1), nbins).round().astype(int), max_x + 1])
    y_edges = np.unique(np.r_[0, 1, np.logspace(0, np.log10(max_y + 1), nbins).round().astype(int), max_y + 1])

    B = np.zeros((len(x_edges) - 1, len(y_edges) - 1), dtype=float)
    tot = 0.0

    for u, v, d in G.edges(data=True):
        w = float(d.get(edge_weight, 1.0))
        i = np.searchsorted(x_edges, dx[u], side="right") - 1
        j = np.searchsorted(y_edges, dy[v], side="right") - 1
        B[i, j] += w
        tot += w

    if tot > 0:
        B /= tot

    return B, x_edges, y_edges

