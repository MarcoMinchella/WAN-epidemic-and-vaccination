"""###Simulation

Here we look at the disease's parameters: σ is the Exposed to Infected rate (1/latent period), γ is the recovery rate (1/infectious period) while β is calculated with the R0 paramater (basic reproduction number) roughly equal to β/γ, by setting a specific R0 we can find β by doing R0*γ.
"""

def run_simulation_on_network(
    network,
    init_node="WUH",
    simulation_length=365,
    beta=1.5,
    gamma=1 / 4.0,
    sigma=1 / 6.0,
    dt=1,
    region_of_node=None,
    region_thresholds=None,
    region_titles=None,
    snapshot_every=1,
    plot_community_graphs=False,
    plot_world_nodes=False,
    animation=False,
):

    print("Infection parameters: beta=",beta," sigma=",sigma, "gamma=",gamma)
    print("R0=",beta/gamma)

    initialize_network(network)
    infect_patient_zero(network, init_node)
    peak = 0
    peak_population = 0
    time_to_peak = 0
    time_to_peak_pop = 0
    TOTAL_NODES = network.number_of_nodes()
    time_to_25 = None
    time_to_50 = None
    infected_at_25 = None
    infected_at_50 = None
    duration = 0
    end_pandemic = False
    flag_10,flag_25,flag_50 = False,False,False
    contained = True
    contained_25 = True
    contained_10 = True

    ever_infected_nodes = []

    #Active nodes, those with E or I population
    active_nodes_ids = [init_node]

    #Time axis
    times = np.arange(simulation_length + 1) * dt
    compartments = ["S", "E", "I", "R"]

    #Regions
    if region_of_node is None:
        region_labels = []
    else:
        region_labels = sorted(set(region_of_node.values()))

    all_regions = ["WORLD"] + region_labels

    hist = {
        region: {
            comp: np.zeros(simulation_length + 1, dtype=int)
            for comp in compartments
        }
        for region in all_regions
    }

    if region_thresholds is None:
        region_thresholds = {}
    if region_titles is None:
        region_titles = {}

    snapshots = []
    snapshots.append({
    n: (network.nodes[n]["Status"],
        network.nodes[n]["I"],
        network.nodes[n]["S"] + network.nodes[n]["E"] +
        network.nodes[n]["I"] + network.nodes[n]["R"])
    for n in network.nodes})

    cumulative_infected_nodes = np.array([init_node])
    count_cumulative = [len(cumulative_infected_nodes)]
    count_active_nodes = [len(active_nodes_ids)]

    for day in range(simulation_length):
        #Nodes that remain active after intra-node SEIR
        duration += 1
        next_active_ids_after_seir = []

        #INTRA-NODE SEIR (ON ACTIVE NODES)
        for i in active_nodes_ids:
            S = network.nodes[i]["S"]
            E = network.nodes[i]["E"]
            I = network.nodes[i]["I"]
            R = network.nodes[i]["R"]

            S, E, I, R = step_SEIR_integer(
                S, E, I, R,
                beta, sigma, gamma,
                dt=dt, rng=None, vaccination_on=False
            )

            network.nodes[i]["S"] = S
            network.nodes[i]["E"] = E
            network.nodes[i]["I"] = I
            network.nodes[i]["R"] = R

            #Status update
            if E > 0:
                network.nodes[i]["Status"] = "E"
                next_active_ids_after_seir.append(i)
            if I > 0:
                network.nodes[i]["Status"] = "I"
                next_active_ids_after_seir.append(i)
            elif S > 0 and E == 0 and I == 0:
                network.nodes[i]["Status"] = "S"
            elif S == 0 and E == 0 and I == 0:
                network.nodes[i]["Status"] = "R"

        active_nodes_ids = list(set(next_active_ids_after_seir))
        cumulative_infected_nodes = np.unique(np.concatenate((cumulative_infected_nodes,active_nodes_ids)))
        count_cumulative.append(len(cumulative_infected_nodes))

        #INTER-NODE INFECTIONS
        neighbors_to_check = get_subsceptible_successors(network,active_nodes_ids)
        newly_infected_nodes, _ = compute_new_infections(network,neighbors_to_check)
        active_nodes_ids = list(set(active_nodes_ids + newly_infected_nodes))
        count_active_nodes.append(len(active_nodes_ids))

        if len(active_nodes_ids) == 0:
            end_pandemic = True
            break

        if len(active_nodes_ids) > peak:
            peak = len(active_nodes_ids)
            peak_population = np.sum(network.nodes[n]["I"] for n in network.nodes)
            time_to_peak = day

        if (len(cumulative_infected_nodes) >= int(TOTAL_NODES*0.1)) and flag_10==False:
            flag_10=True
            contained_10 = False

        if (len(cumulative_infected_nodes) >= int(TOTAL_NODES*0.25)) and flag_25==False:
            flag_25=True
            time_to_25 = day
            contained_25 = False
            infected_at_25 = np.sum(network.nodes[n]["I"] for n in network.nodes)

        if (len(cumulative_infected_nodes) >= int(TOTAL_NODES*0.5)) and flag_50==False:
            flag_50=True
            time_to_50 = day
            contained = False
            infected_at_50 = np.sum(network.nodes[n]["I"] for n in network.nodes)

        day_world = {c: 0 for c in compartments}

        #Reset region daily totals
        day_region = {
            region: {c: 0 for c in compartments}
            for region in region_labels
        }

        for n_id, data in network.nodes(data=True):
            S = data["S"]
            E = data["E"]
            I = data["I"]
            R = data["R"]

            #Totals
            day_world["S"] += S
            day_world["E"] += E
            day_world["I"] += I
            day_world["R"] += R

            #Region totals (if mapping is provided)
            if region_of_node is not None:
                region = region_of_node.get(n_id)
                if region in day_region:
                    day_region[region]["S"] += S
                    day_region[region]["E"] += E
                    day_region[region]["I"] += I
                    day_region[region]["R"] += R

