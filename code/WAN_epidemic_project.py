def vaccinate_nodes(network, nodes_to_vaccinate):
    vaccinated_network = network.copy()
    vaccination_cost = 0
    for node in nodes_to_vaccinate:
        if node not in vaccinated_network:
            continue

        for _, neighbor in vaccinated_network.edges(node):
            vaccination_cost += vaccinated_network[node][neighbor]["weight"]
            vaccinated_network[node][neighbor]["weight"] = 0.0

        for neighbor, _ in vaccinated_network.in_edges(node):
                vaccination_cost += vaccinated_network[neighbor][node]["weight"]
                vaccinated_network[neighbor][node]["weight"] = 0.0

    return vaccinated_network, vaccination_cost

