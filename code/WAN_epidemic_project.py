def mixing_ratio(B, counts=None, min_count=5):
    e = B / B.sum()
    qx = e.sum(axis=1, keepdims=True)
    qy = e.sum(axis=0, keepdims=True)
    null = qx @ qy
    with np.errstate(divide="ignore", invalid="ignore"):
        R = np.where(null > 0, e / null, np.nan)
    R[~np.isfinite(R)] = np.nan
    R[e == 0] = np.nan
    if counts is not None:
        R[counts < min_count] = np.nan
    return R


