import heapq

def directed_flow_ci_targets(G,weight="weight",l= 2,n_remove= 50,g_mode="log",tau=1.0):
    if l < 1:
        raise ValueError("Use l>=1 for a meaningful frontier")

    working = G.copy()
    removed = set()
    removed_list = []

    def out_strength(graph, u):
        s = 0.0
        for _, v, data in graph.out_edges(u, data=True):
            s += float(data.get(weight, 1.0))
        return s

    def g(x):
        if g_mode == "raw":
            return max(x, 0.0)
        if g_mode == "minus_tau":
            return max(x - tau, 0.0)
        if g_mode == "log":
            return math.log1p(max(x, 0.0))
        raise ValueError("g_mode must be 'raw', 'minus_tau', or 'log'")

    def frontier_out(graph, src, dist):
        lengths = nx.single_source_shortest_path_length(graph, src, cutoff=dist)
        return [n for n, d in lengths.items() if d == dist]

    def score(graph, u):
        gu = g(out_strength(graph, u))
        if gu == 0.0:
            return 0.0
        fr = frontier_out(graph, u, l)
        if not fr:
            return 0.0
        return gu * sum(g(out_strength(graph, v)) for v in fr)

    current = {u: score(working, u) for u in working.nodes()}
    heap = [(-val, u) for u, val in current.items()]
    heapq.heapify(heap)

    while len(removed_list) < n_remove and heap and working.number_of_nodes() > 0:
        neg_val, u = heapq.heappop(heap)
        if u in removed or u not in working:
            continue
        if -neg_val != current.get(u, None):
            continue

        # affected nodes
        affected = list(nx.single_source_shortest_path_length(working, u, cutoff=l+1).keys())

        working.remove_node(u)
        removed.add(u)
        removed_list.append(u)

        for v in affected:
            if v in working and v not in removed:
                new_val = score(working, v)
                current[v] = new_val
                heapq.heappush(heap, (-new_val, v))

    return removed_list

