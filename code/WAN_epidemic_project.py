"""##The epidemic model

####Helper functions

One time-step of integer SEIR with binomial transitions and optional vaccination. Methods for computing intra-node infection have been added as well.
"""

def step_SEIR_integer(S,E,I,R,beta,sigma,gamma,dt=1.0,rng=None,vaccination_on=False,nu=0.0):

    if rng is None:
        rng = np.random.default_rng()

    N = S + E + I + R
    if N == 0:
        return S, E, I, R

    #SUBSCEPTIBLE DYNAMICS
    # Infection hazard per susceptible:
    lambda_inf = beta * I / N

    # Vaccination hazard per susceptible:
    lambda_vac = nu if vaccination_on else 0.0

    # Total hazard from either infection or vaccination
    lambda_tot = lambda_inf + lambda_vac

    X = 0  # new exposures
    V = 0  # new vaccinations

    if lambda_tot > 0.0:
        # Probability that a susceptible experiences any event in [t, t+dt]
        p_any = 1.0 - math.exp(-lambda_tot * dt)
        p_any = min(max(p_any, 0.0), 1.0)

        # How many susceptibles experience some event?
        W = rng.binomial(S, p_any)

        # Conditional probability that the event is infection
        p_inf_given_any = lambda_inf / lambda_tot

        # Integer flows:
        X = rng.binomial(W, p_inf_given_any)  # S -> E (infection)
        V = W - X                             # S -> R (recovery)
    else:
        # No infection, no vaccination: X = V = 0
        W = 0

    #E -> I
    p_EI = 1.0 - math.exp(-sigma * dt)
    p_EI = min(max(p_EI, 0.0), 1.0)
    Y = rng.binomial(E, p_EI)  # new infections (E -> I)

    #I -> R
    p_IR = 1.0 - math.exp(-gamma * dt)
    p_IR = min(max(p_IR, 0.0), 1.0)
    Z = rng.binomial(I, p_IR)  # new removals (I -> R)

    #Updates
    S_next = S - W           # W = X + V leave S
    E_next = E + X - Y
    I_next = I + Y - Z
    R_next = R + Z + V       # Vaccinated people go to R

    # Sanity checks
    if S_next < 0 or E_next < 0 or I_next < 0 or R_next < 0:
      print("ERROR: S:",S," E:",E," I:",I," R:",R)
    assert S_next >= 0 and E_next >= 0 and I_next >= 0 and R_next >= 0
    assert S_next + E_next + I_next + R_next == N

    return S_next, E_next, I_next, R_next

def get_subsceptible_successors(G,infected_node_ids):
    unique_S_successors = []
    for node_id in infected_node_ids:
      successors = list(G.successors(node_id))
      for s in successors:
          if G.nodes[s]["S"]>0:
              unique_S_successors.append(s)
    return list(set(unique_S_successors))

def compute_new_infections(G,subsceptible_successors_ids):
  flights_arr = []
  new_infections = []
  edges = []
  for node_id in subsceptible_successors_ids:
    safety_probability_total = 1
    predecessors = list(G.predecessors(node_id))
    for p in predecessors:
      if G.nodes[p]["I"]>0:
        mean_flights = G.get_edge_data(p,node_id)["weight"]
        #Multiply by edge weight since it is the sum of parallel flights

        #CANCELLATIONS
        THRESHOLD = 20 #if mean flights are below this then Poisson
        if mean_flights <= THRESHOLD:
          flights = np.random.poisson(lam=mean_flights)
        else:
          scheduled = int(round(mean_flights))
          flights = np.random.binomial(scheduled, p=0.98) #2% cancellations

        node_population=G.nodes[p]["S"]+G.nodes[p]["E"]+G.nodes[p]["I"]+G.nodes[p]["R"]
        safety_probability = (1-G.nodes[p]["I"]/node_population)**(flights)
        safety_probability_total = safety_probability_total*safety_probability

    infection_probability = 1-safety_probability_total

    result=np.random.rand()
    if result < infection_probability:
        arrived_infected = int(np.random.uniform(low=1,high=10))
        if G.nodes[node_id]["S"] >= arrived_infected:
         G.nodes[node_id]["S"] = G.nodes[node_id]["S"]-arrived_infected
         G.nodes[node_id]["E"] = G.nodes[node_id]["E"]+arrived_infected
         G.nodes[node_id]["Status"] = "E"
         new_infections.append(node_id)
         edges.append((p,node_id))
        elif G.nodes[node_id]["S"] >= 1 and G.nodes[node_id]["S"] < arrived_infected:
         G.nodes[node_id]["S"] = G.nodes[node_id]["S"]-1
         G.nodes[node_id]["E"] = G.nodes[node_id]["E"]+1
         G.nodes[node_id]["Status"] = "E"
         new_infections.append(node_id)
         edges.append((p,node_id))

  return new_infections,edges

