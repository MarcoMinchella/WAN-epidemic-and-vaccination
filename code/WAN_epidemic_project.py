def _log_edges_from_values(values, nbins=35):
    vals = np.asarray([v for v in values if v > 0], dtype=float)
    if len(vals) == 0:
        return np.array([0.0, 1.0, np.inf])
    vmin, vmax = vals.min(), vals.max()
    edges_pos = np.logspace(np.log10(vmin), np.log10(vmax), nbins)
    edges = np.unique(np.concatenate(([0.0], edges_pos, [np.inf])))
    return edges

def _log_edges_from_int(max_k, nbins=35):
    if max_k < 1:
        return np.array([0, 1, max_k+1], dtype=int)
    edges = np.unique(np.round(np.logspace(0, np.log10(max_k+1), nbins)).astype(int))
    edges = np.unique(np.concatenate(([0, 1], edges, [max_k+1])))
    return edges

def directed_log_binned_mixing(G, x_mode, y_mode, edge_weight="weight",
                               nbins=35, use_strength=True, return_counts=False):
    # node feature used for binning
    if use_strength:
        x_feat = dict(G.out_degree(weight=edge_weight)) if x_mode == "out" else dict(G.in_degree(weight=edge_weight))
        y_feat = dict(G.out_degree(weight=edge_weight)) if y_mode == "out" else dict(G.in_degree(weight=edge_weight))
        x_edges = _log_edges_from_values(x_feat.values(), nbins)
        y_edges = _log_edges_from_values(y_feat.values(), nbins)
    else:
        x_feat = dict(G.out_degree(weight=None)) if x_mode == "out" else dict(G.in_degree(weight=None))
        y_feat = dict(G.out_degree(weight=None)) if y_mode == "out" else dict(G.in_degree(weight=None))
        x_edges = _log_edges_from_int(max(x_feat.values(), default=0), nbins)
        y_edges = _log_edges_from_int(max(y_feat.values(), default=0), nbins)

    B = np.zeros((len(x_edges) - 1, len(y_edges) - 1), dtype=float)
    C = np.zeros_like(B)          # raw edge counts per cell
    total_w = 0.0

    for u, v, d in G.edges(data=True):
        w = float(d.get(edge_weight, 1.0)) if edge_weight else 1.0
        xu = x_feat.get(u, 0.0)
        yv = y_feat.get(v, 0.0)
        i = np.searchsorted(x_edges, xu, side="right") - 1
        j = np.searchsorted(y_edges, yv, side="right") - 1
        if 0 <= i < B.shape[0] and 0 <= j < B.shape[1]:
            B[i, j] += w
            C[i, j] += 1
            total_w += w

    if total_w > 0:
        B /= total_w

    return (B, C) if return_counts else B

