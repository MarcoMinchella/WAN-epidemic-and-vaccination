def giant_sizes_directed(G):
    if G.number_of_nodes() == 0:
        return 0, 0
    gwcc = max(nx.weakly_connected_components(G), key=len)
    gscc = max(nx.strongly_connected_components(G), key=len)
    return len(gwcc), len(gscc)

def removal_curve(G, node_order, steps=50):
    G = G.copy()
    N0 = G.number_of_nodes()
    gwcc0, gscc0 = giant_sizes_directed(G)

    # fractions to remove
    f_grid = np.linspace(0, 1, steps+1)
    gwcc_frac = []
    gscc_frac = []

    #remove incrementally
    k_prev = 0
    for f in f_grid:
        k = int(round(f * N0))
        if k > k_prev:
            to_remove = node_order[k_prev:k]
            G.remove_nodes_from(to_remove)
            k_prev = k

        gwcc, gscc = giant_sizes_directed(G)
        gwcc_frac.append(gwcc / N0)
        gscc_frac.append(gscc / N0)

    return f_grid, np.array(gwcc_frac), np.array(gscc_frac)

def static_ranking(G, method="pagerank", weight="weight", alpha=0.85, max_iter=1000, tol=1e-8):

    if method == "out_degree":
        score = dict(G.out_degree())
    elif method == "w_out_degree":
        score = dict(G.out_degree(weight=weight))
    elif method == "pagerank":
        score = nx.pagerank(G, alpha=alpha, weight=weight,
                            max_iter=max_iter, tol=tol)
    elif method == "betweenness":
        for u, v, d in G.edges(data=True):
            d["dist"] = 1.0 / d["weight"]
        score = nx.betweenness_centrality(G, weight="dist", normalized=True)
    elif method == "pr_wdeg_combo":
        return get_top_outdegree_and_pagerank_targets_robustness(
            G, k=G.number_of_nodes(), weight=weight, alpha=alpha,
            max_iter=max_iter, tol=tol
        )
    else:
        raise ValueError("Unknown method")

    return [n for n, _ in sorted(score.items(), key=lambda x: x[1], reverse=True)]

def get_top_outdegree_and_pagerank_targets_robustness(G, k=100, weight="weight", alpha=0.85,
                                           max_iter=1000, tol=1e-8):
    pr = nx.pagerank(G, alpha=alpha, weight=weight, max_iter=max_iter, tol=tol)
    wout = dict(G.out_degree(weight=weight))

    nodes = list(G.nodes())
    k = min(k, len(nodes))

    pr_vals = {n: float(pr.get(n, 0.0)) for n in nodes}
    wout_vals = {n: float(wout.get(n, 0.0)) for n in nodes}

    pr_min, pr_max = min(pr_vals.values()), max(pr_vals.values())
    wo_min, wo_max = min(wout_vals.values()), max(wout_vals.values())

    def norm(x, a, b):
        return 0.0 if b == a else (x - a) / (b - a)

    score = {
        n: norm(pr_vals[n], pr_min, pr_max) * norm(wout_vals[n], wo_min, wo_max)
        for n in nodes
    }

    return [n for n, _ in sorted(score.items(), key=lambda x: x[1], reverse=True)[:k]]

